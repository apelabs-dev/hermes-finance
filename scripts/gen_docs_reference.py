"""Write the docs site's generated reference pages from the code, so they can't drift from it:

    python scripts/gen_docs_reference.py            # (re)write the pages below
    python scripts/gen_docs_reference.py --check    # write nothing; exit 1 when a checked-in page differs

    docs/reference/cli.md            every `finance` command's --help (cli.build_parser())
    docs/reference/tools.md          every finance_* agent tool's name, kind, description and argument schema
                                     (tooldefs.TOOLS: the Hermes plugin and the MCP server advertise exactly these)
    docs/reference/settings-keys.md  every app setting's key and default (prefs.SPEC), the AI presets, the valuation caps

Stdlib only: it puts src/ on sys.path itself and writes no bytecode, so the app's .venv and the docs build's venv both
run it. mkdocs.yml's hook (scripts/mkdocs_hooks.py) runs stale() before every build and fails the build on a stale page.
Help text is laid out at a fixed width, and only by Python 3.12 (the project's version): argparse's layout changes
between Python versions, so another one would rewrite every page. Nothing here reads a database, a key file or the
network.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference"
WIDTH = "100"
PYTHON = (3, 12)
HEADER = ("<!-- Generated by scripts/gen_docs_reference.py from {source}. Do not edit by hand: change the code, then run\n"
          "     python scripts/gen_docs_reference.py (mkdocs build fails while this page is stale). -->\n")


def _app():
    """The app's modules, from this checkout's src/, with the help laid out the same everywhere."""
    if sys.version_info[:2] != PYTHON:
        raise SystemExit(f"gen_docs_reference: needs Python {PYTHON[0]}.{PYTHON[1]} (argparse's layout differs between "
                         f"versions), this is {sys.version.split()[0]}")
    os.environ["COLUMNS"] = WIDTH          # argparse wraps help at the terminal's width
    os.environ.setdefault("NO_COLOR", "1")
    sys.dont_write_bytecode = True
    src = str(ROOT / "src")
    if src not in sys.path:
        sys.path.insert(0, src)
    from hermes_finance import cli, config, prefs, tooldefs
    return cli, config, prefs, tooldefs


# --- CLI ---------------------------------------------------------------------------------------------------------------

def _subcommands(parser: argparse.ArgumentParser) -> list[tuple[str, str, argparse.ArgumentParser]]:
    """(name, one-line help, parser) of each subcommand, in the parser's order."""
    out = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {a.dest: a.help or "" for a in action._choices_actions}
            out += [(name, helps.get(name, ""), sub) for name, sub in action.choices.items()]
    return out


def _walk(parser: argparse.ArgumentParser, path: list[str]):
    yield path, parser
    for name, _, sub in _subcommands(parser):
        yield from _walk(sub, [*path, name])


def _anchor(path: list[str]) -> str:
    return "-".join(path)


def cli_page(cli) -> str:
    root = cli.build_parser()
    lines = [HEADER.format(source="hermes_finance.cli.build_parser()"), "# CLI reference", "",
             "Every `finance` command, with its `--help` exactly as the code prints it. Run them as "
             "`uv run finance <command>` from the checkout. `-v` before the command (`finance -v sync`) logs progress "
             "to stderr.", "", "| Command | What it does |", "|---|---|"]
    for name, help_, _ in _subcommands(root):   # (a help string is a %-format: argparse prints "%%" as "%")
        lines.append(f"| [`{name}`](#{_anchor(['finance', name])}) | {help_.replace('%%', '%').replace('|', '/')} |")
    lines.append("")
    for path, parser in _walk(root, ["finance"]):
        level = "##" if len(path) <= 2 else "###"   # `finance` and its commands; a command's own subcommands below
        lines += [f"{level} `{' '.join(path)}` {{#{_anchor(path)}}}", "", "```text", parser.format_help().rstrip(),
                  "```", ""]
    return "\n".join(lines)


# --- agent tools -------------------------------------------------------------------------------------------------------

def _kind(t) -> str:
    return "write (needs approval)" if t.write else "action" if t.action else "read"


def _type(spec: dict) -> str:
    kinds = spec.get("type")
    kinds = kinds if isinstance(kinds, list) else [kinds]
    text = " or ".join(str(k) for k in kinds)
    if "items" in spec:
        text += f" (items: {spec['items'].get('type')})"
    return text


def _limits(spec: dict) -> str:
    out = []
    if "enum" in spec:
        out.append("one of " + ", ".join(f"`{v}`" for v in spec["enum"]))
    for key, word in (("minimum", "min"), ("maximum", "max"), ("minItems", "min items"), ("maxItems", "max items")):
        if key in spec:
            out.append(f"{word} {spec[key]}")
    return "; ".join(out)


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def tools_page(tooldefs) -> str:
    lines = [HEADER.format(source="hermes_finance.tooldefs.TOOLS"), "# Agent tools reference", "",
             f"The {len(tooldefs.TOOLS)} `finance_*` tools. One definition each, in `src/hermes_finance/tooldefs.py`, "
             "shared by the Hermes plugin (`hermes_plugin/`) and the MCP server (`finance mcp`, and `/mcp` on "
             "`finance serve`). A read tool answers exactly what its `finance <command> --json` prints.", "",
             "- **read**: opens the database read-only and never calls Plaid. Listed everywhere.",
             "- **action** (`finance_sync`): syncs with Plaid now. It changes nothing you entered, so it runs without "
             "an approval, except `refresh=true` on a paid Plaid plan (Plaid bills each refresh), which needs one.",
             "- **write**: in the Hermes plugin, Hermes asks for your approval first (and blocks it where nobody can "
             "answer). Over MCP these are listed only after `finance mcp allow-writes on`, and a call is only saved as "
             "a pending action you approve in Settings.", "",
             "The MCP server's instructions to every client:", "", f"> {tooldefs.instructions()}", "",
             "| Tool | Kind | Same as |", "|---|---|---|"]
    for t in tooldefs.TOOLS.values():
        same = f"`finance {t.command} --json`" if t.command else "-"
        lines.append(f"| [`{t.name}`](#{t.name.replace('_', '-')}) | {_kind(t)} | {same} |")
    lines.append("")
    for t in tooldefs.TOOLS.values():
        schema = t.schema()
        lines += [f"## `{t.name}` {{#{t.name.replace('_', '-')}}}", "", t.description, "",
                  f"Kind: {_kind(t)}." + (f" Same answer as `finance {t.command} --json`." if t.command else ""), ""]
        props = schema.get("properties", {})
        if not props:
            lines += ["No arguments.", ""]
            continue
        required = set(schema.get("required", []))
        lines += ["| Argument | Type | Required | Limits | Description |", "|---|---|---|---|---|"]
        for name, spec in props.items():
            lines.append(f"| `{name}` | {_cell(_type(spec))} | {'yes' if name in required else 'no'} | "
                         f"{_cell(_limits(spec))} | {_cell(spec.get('description', ''))} |")
        lines += ["", "<details><summary>JSON schema</summary>", "", "```json",
                  json.dumps(schema, indent=2, ensure_ascii=False), "```", "", "</details>", ""]
    return "\n".join(lines)


# --- settings keys -----------------------------------------------------------------------------------------------------

def settings_page(config, prefs) -> str:
    lines = [HEADER.format(source="hermes_finance.prefs and hermes_finance.config"), "# Settings keys", "",
             "Every setting the app stores, one JSON value per key in the database's `settings` table, with its default. "
             "A missing or invalid value reads as the default. The Settings page saves them; `finance settings --json` "
             "prints the ones marked *shown* (never a key, password or whole identity); the *internal* ones are used by "
             "the app itself (`access.*` is printed there in a summarized form). See [Settings](../settings.md) "
             "for what each one does.", "", "| Key | Default | Shown |", "|---|---|---|"]
    for key, spec in prefs.SPEC.items():
        lines.append(f"| `{key}` | `{json.dumps(spec.default)}` | {'shown' if spec.public else 'internal'} |")
    lines += ["", "`valuations.*`: the default above is only what an unsaved key reads as. What is in effect comes from "
              "`config.free_sources()`: a flag in the env file, else the switch saved on the Settings page, else a new "
              "install's default (see [Valuation sources](#valuation-sources)). `finance settings` prints that.",
              "", "## AI provider presets", "", "| Preset | Endpoint |", "|---|---|"]
    lines += [f"| `{k}` | {f'`{v}`' if v else '(you type it)'} |" for k, v in prefs.AI_PRESETS.items()]
    lines += ["", "## Region", "", "Currencies (display only: amounts are never converted): "
              + ", ".join(f"`{c}`" for c in prefs.CURRENCIES) + ".", "",
              "Locales: " + ", ".join(f"`{c}`" for c in prefs.LOCALES) + ".", "",
              "## Valuation sources", "",
              "Keyless public sources for car and home values and pictures. A source's calls are counted before they are "
              "sent, failed ones too, and it stops for the month at its cap.", "",
              "| Provider | Calls per month (cap) | Block after a refusal (days) |", "|---|---|---|"]
    for provider, cap in config.API_CAPS.items():
        block = config.BLOCK_DAYS.get(provider, "rest of the month")
        lines.append(f"| `{provider}` | {cap} | {block} |")
    lines += ["", "On / off switches: the Settings page (Valuations), or a flag in the env file, which wins: "
              + ", ".join(f"`{v}=0`" for v in config.FREE_SOURCE_NAMES.values()) + ". A new install starts with "
              + ", ".join(f"{k} {'on' if on else 'off'}" for k, on in config.FREE_SOURCES_DEFAULT.items()) + ".", ""]
    return "\n".join(lines)


# --- run ---------------------------------------------------------------------------------------------------------------

def pages() -> dict[Path, str]:
    cli, config, prefs, tooldefs = _app()
    return {OUT / "cli.md": cli_page(cli), OUT / "tools.md": tools_page(tooldefs),
            OUT / "settings-keys.md": settings_page(config, prefs)}


def stale() -> list[str]:
    """The generated pages that are missing or differ from what the code gives (repo-relative paths)."""
    return [str(p.relative_to(ROOT)) for p, text in pages().items() if not p.exists() or p.read_text() != text]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when a page is stale")
    args = ap.parse_args(argv)
    if args.check:
        bad = stale()
        for p in bad:
            print(f"stale: {p} (run python scripts/gen_docs_reference.py)")
        if not bad:
            print("generated reference pages are up to date")
        return 1 if bad else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, text in pages().items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
